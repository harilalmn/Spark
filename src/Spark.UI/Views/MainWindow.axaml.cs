    /// <summary>Command-line options, chiefly the benchmark switches.</summary>
    public StartupOptions Options { get; set; } = StartupOptions.Default;

    private void OnOpened(object? sender, EventArgs e)
    {
        // Before anything asks for a frame: the switch has to be in place before the first GL
        // callback, or a context is created and then abandoned.
        Viewport.ForceSoftwareRenderer = Options.ForceSoftwareRenderer;

        if (Options.CollapseFirst > 0)
        {
            for (int slot = 0; slot < Options.CollapseFirst && slot < Canvas.Graph.Nodes.Count; slot++)
            {
                Canvas.SelectAlso(slot);
            }

            OnCollapseSelection(this, new RoutedEventArgs());
        }

        if (Options.OpensHelp)
        {
            OpenHelp();
            _help?.Navigate(Options.HelpTopic);
        }

        if (Options.OpensPackages)
        {
            // The query is put on the model before the window is built, so the search box shows
            // what was searched for. The window reads it once and then leaves it alone, because a
            // box that re-synced would erase whatever the user was halfway through typing.
            if (Model is { } packageModel && !string.IsNullOrWhiteSpace(Options.PackageQuery))
            {
                packageModel.Packages().Query = Options.PackageQuery;
            }

            OpenPackages();

            if (!string.IsNullOrWhiteSpace(Options.PackageQuery) && _packages is not null)
            {
                _ = SearchThenPrepareAsync(_packages, Options.PreparePackage);
            }

            // The tab comes to the front whenever --reference was given at all, so passing it an
            // empty value opens the list without prompting about anything. Choosing is separate.
            if (Options.ReferenceAssembly is not null && _packages is not null)
            {
                _packages.ShowLocalAssemblies();

                if (!string.IsNullOrWhiteSpace(Options.ReferenceAssembly))
                {
                    _packages.Local.Choose(Options.ReferenceAssembly);
                }
            }
        }

        if (Options.OpenAbout)
        {
            _about = new AboutWindow(
                typeof(MainWindow).Assembly.GetName().Version?.ToString(),
                Spark.Api.BrepKernel.Current is Spark.Api.UnavailableBrepKernel
                    ? null
                    : Spark.Api.BrepKernel.Current.Description);

            _about.Show(this);
        }

        if (Options.SyntheticNodeCount > 0)
        {
            LoadSynthetic(Options.SyntheticNodeCount);
        }
        else
        {
            // A file named on the command line was already opened by the view model's
            // constructor, so there is exactly one graph adoption and one evaluation.
            Canvas.ZoomToFit();
        }

        UpdateStatus();
        UpdateMissingBanner();

        if (Options.IsBenchmark)
        {
            StartBenchmark(Options.BenchmarkFrames);
            return;
        }

        if (Options.IsScreenshot)
        {
            // The demo graph is evaluated on construction; the capture waits for that run to have
            // landed, because a screenshot taken before the first evaluation shows an empty
            // viewport and proves nothing at all.
            _ = CaptureWhenReadyAsync(Options.ScreenshotPrefix!);
            return;
        }

        Viewport.ZoomToFit();
    }

    private async Task CaptureWhenReadyAsync(string prefix)
    {
        if (Model is { } model)
        {
            await model.EvaluateAsync().ConfigureAwait(true);
        }


        Canvas.ZoomToFit();
        Viewport.ZoomToFit();
        StartCapture(prefix);
    }

    /// <summary>
    /// Writes a picture of the shell and a picture of the viewport, then exits.
    /// </summary>
    /// <param name="prefix">The file path prefix the two images are written under.</param>
    /// <remarks>
    /// The two images are taken by different means on purpose. The shell is rendered through
    /// Avalonia's own render-target path, which captures the immediate-mode canvas exactly as the
    /// compositor sees it. The viewport is a read-back from whichever backend drew it — a
    /// <c>glReadPixels</c> off the GPU, or the software rasteriser's own framebuffer — because the
    /// GL surface is composited separately and does not appear in a visual-tree render, and
    /// because a read-back is the only way to answer "is it drawing anything?" on a machine whose
    /// session is locked, which is also the situation in CI.
    /// </remarks>
    private void StartCapture(string prefix)
    {
        if (Options.BenchmarkZoom > 0)
        {
            // Centre on the graph after zooming. Setting the zoom alone scales about the world
            // origin, which at any zoom above the fit takes every node off screen — and a
            // screenshot switch that reliably photographs empty canvas is worse than none.
            Canvas.Transform.Zoom = Options.BenchmarkZoom;
            Canvas.CentreOn(Canvas.Graph.ComputeBounds());
        }

        Viewport.RequestCapture();

        // Wait for a frame, not for a clock. Which backend services the capture is not something
        // this caller can predict - OpenGL may come up at once, or never - and the software
        // fallback only commits after the viewport has waited out its patience for a GL callback
        // that is not coming. A fixed delay was tuned to the GL case and silently produced no
        // image at all on a machine where GL never initialises, which is precisely the machine the
        // fallback exists for.
        WaitForCapture(prefix, DateTime.UtcNow + TimeSpan.FromSeconds(6));
    }

    /// <summary>
    /// Polls until a frame has been captured or the deadline passes, then writes the images.
    /// </summary>
    /// <param name="prefix">The file path prefix.</param>
    /// <param name="deadline">When to give up and write whatever there is.</param>
    /// <remarks>
    /// Polling rather than an event, because the two backends signal completion in different
    /// places and a caller that had to know which one was active would be back to guessing. The
    /// deadline is generous: this path runs in CI, where a cold GPU driver is slower than anything
    /// a developer sees, and the cost of waiting is a few seconds on a run that then exits.
    /// </remarks>
    private void WaitForCapture(string prefix, DateTime deadline)
    {
        if (Viewport.HasCapture || DateTime.UtcNow >= deadline)
        {
            WriteCaptures(prefix);
            return;
        }

        // Ask again: a frame is only produced when one is requested, and a viewport with nothing
        // changing produces none.
        Viewport.RequestCapture();

        DispatcherTimer.RunOnce(() => WaitForCapture(prefix, deadline), TimeSpan.FromMilliseconds(150));
    }

    private void WriteCaptures(string prefix)
    {
        UpdateStatus();

        int width = Math.Max(1, (int)Bounds.Width);
        int height = Math.Max(1, (int)Bounds.Height);

        using (RenderTargetBitmap shell = new(new PixelSize(width, height), new Vector(96, 96)))
        {
            shell.Render(this);
            shell.Save(prefix + "-shell.png", PngBitmapEncoderOptions.Default);
        }

        Console.WriteLine(string.Create(
            CultureInfo.InvariantCulture, $"wrote {prefix}-shell.png ({width}x{height})"));

        if (_about is not null)
        {
            int aboutWidth = Math.Max(1, (int)_about.Bounds.Width);
            int aboutHeight = Math.Max(1, (int)_about.Bounds.Height);

            using RenderTargetBitmap about = new(new PixelSize(aboutWidth, aboutHeight), new Vector(96, 96));
            about.Render(_about);
            about.Save(prefix + "-about.png", PngBitmapEncoderOptions.Default);

            Console.WriteLine(string.Create(
                CultureInfo.InvariantCulture, $"wrote {prefix}-about.png ({aboutWidth}x{aboutHeight})"));
        }

        if (_help is not null)
        {
            int helpWidth = Math.Max(1, (int)_help.Bounds.Width);
            int helpHeight = Math.Max(1, (int)_help.Bounds.Height);

            using RenderTargetBitmap help = new(new PixelSize(helpWidth, helpHeight), new Vector(96, 96));
            help.Render(_help);
            help.Save(prefix + "-help.png", PngBitmapEncoderOptions.Default);

            Console.WriteLine(string.Create(
                CultureInfo.InvariantCulture,
                $"wrote {prefix}-help.png ({helpWidth}x{helpHeight}); topic {_help.CurrentTopicId}"));
        }

        if (_packages is not null)
        {
            int packagesWidth = Math.Max(1, (int)_packages.Bounds.Width);
            int packagesHeight = Math.Max(1, (int)_packages.Bounds.Height);

            using RenderTargetBitmap packages = new(
                new PixelSize(packagesWidth, packagesHeight), new Vector(96, 96));
            packages.Render(_packages);
            packages.Save(prefix + "-packages.png", PngBitmapEncoderOptions.Default);

            Console.WriteLine(string.Create(
                CultureInfo.InvariantCulture,
                $"wrote {prefix}-packages.png ({packagesWidth}x{packagesHeight})"));
        }

        byte[]? pixels = Viewport.TakeCapture(out int glWidth, out int glHeight);
        if (pixels is null)
        {
            // Print the status here too. This is the one case where a reader most needs to know
            // what the viewport thought it was doing, and it was the one case that did not say:
            // the status line came after the image was written, so the failure path skipped it.
            Console.WriteLine("no viewport read-back: neither backend produced a frame.");
            Console.WriteLine(string.Create(
                CultureInfo.InvariantCulture, $"viewport status: {Viewport.Status ?? "no GL callback ran"}"));
            Console.WriteLine(string.Create(
                CultureInfo.InvariantCulture,
                $"software presenting: {Viewport.IsSoftwarePresenting}"));

            Close();
            return;
        }

        using (WriteableBitmap viewport = new(
            new PixelSize(glWidth, glHeight), new Vector(96, 96), PixelFormat.Rgba8888, AlphaFormat.Opaque))
        {
            using (ILockedFramebuffer buffer = viewport.Lock())
            {
                // TakeCapture normalises to top-down rows whichever backend drew the frame, so
                // there is nothing to flip here. It used to flip unconditionally, which was
                // right for GL and would have silently inverted every software capture.
                for (int row = 0; row < glHeight; row++)
                {
                    Marshal.Copy(pixels, row * glWidth * 4, buffer.Address + (row * buffer.RowBytes), glWidth * 4);
                }
            }

            viewport.Save(prefix + "-viewport.png", PngBitmapEncoderOptions.Default);
        }

        Console.WriteLine(string.Create(
            CultureInfo.InvariantCulture,
            $"wrote {prefix}-viewport.png ({glWidth}x{glHeight}); {DescribePixels(pixels)}"));
        Console.WriteLine(string.Create(
            CultureInfo.InvariantCulture, $"viewport status: {Viewport.Status}"));

        Close();
    }

    /// <summary>
    /// Summarises a read-back so the console alone can distinguish "drew a scene" from "cleared to
    /// one colour" and from "drew nothing at all".
    /// </summary>
    /// <param name="rgba">The read-back pixels.</param>
    /// <returns>A one-line description.</returns>
    private static string DescribePixels(byte[] rgba)
    {
        System.Collections.Generic.HashSet<int> distinct = [];
        long luminanceTotal = 0;
        int samples = 0;

        for (int i = 0; i + 3 < rgba.Length; i += 4)
        {
            distinct.Add((rgba[i] << 16) | (rgba[i + 1] << 8) | rgba[i + 2]);
            luminanceTotal += (rgba[i] * 2) + (rgba[i + 1] * 5) + rgba[i + 2];
            samples++;

            if (distinct.Count > 20000)
            {
                break;
            }
        }

        double mean = samples == 0 ? 0 : luminanceTotal / (double)samples / 8.0;
        return string.Create(
            CultureInfo.InvariantCulture,
            $"{distinct.Count} distinct colours, mean luminance {mean:F1}/255");
    }

