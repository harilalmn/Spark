    /// <summary>Creates the window.</summary>
    public MainWindow()
    {
        // InitializeComponent is generated by Avalonia's name generator: it loads the XAML and
        // assigns the x:Name fields. Declaring one by hand here shadows it, the fields stay null,
        // and the first line below throws — which is exactly what happened the first time.
        InitializeComponent();

        // The panes are constructed here rather than declared in the XAML because a Tool's
        // Content is a template (N34): declaring them inline would build them into a namescope
        // this window cannot reach, and everything below reaches them.
        Shell.Factory = _dock;
        Shell.Layout = _dock.Build(new Dictionary<WorkspacePane, object?>
        {
            [WorkspacePane.Library] = _libraryPane,
            [WorkspacePane.Canvas] = _canvasPane,
            [WorkspacePane.Viewport] = _viewportPane,
            [WorkspacePane.Inspector] = _inspectorPane,
        });

        Canvas.ShowFrameStatistics = true;

        // The canvas reports gestures; the view model runs the graph. A view that started an
        // evaluation would be doing it on the thread it draws on (ADR-0005).
        Canvas.GraphChanged += OnCanvasGraphChanged;
        Canvas.SelectionChanged += OnCanvasSelectionChanged;

        // Nothing is selected yet, so Align starts disabled. Left to the first SelectionChanged
        // it would start enabled over an empty selection and do nothing when pressed.
        UpdateAlignAvailability();

        // The library pane cannot see the canvas, and should not: where a node lands depends on
        // what is already on the surface. It asks, and the window is what knows both halves.
        _libraryPane.PlaceRequested += (_, _) => PlaceSelectedLibraryEntry();

        // The pane owns the text box; the canvas owns the pixels; the shell owns the undo stack.
        // The pane tells the window the text changed, and the window tells the other two.
        _inspectorPane.NoteEdited += (_, _) => Canvas.NoteTextEdited();
        _inspectorPane.GroupRenamed += (_, _) => Canvas.GroupTitleEdited();

        // A code block's ports change when its script does, so the canvas has to rebuild its
        // structure rather than merely repaint - which is the one way editing a script differs
        // from editing a note.
        _inspectorPane.ScriptEdited += (_, _) =>
        {
            Canvas.RefreshStructure();
            Canvas.InvalidateVisual();
            _ = Model?.EvaluateAsync();
        };

        DataContextChanged += OnDataContextChanged;
        Opened += OnOpened;
    }

